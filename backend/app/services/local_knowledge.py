def select_industry_template(keyword: str) -> list[TemplateNode] | None:
    normalized = keyword.strip().lower()
    if not normalized:
        return None
    company_template = company_related_template(keyword)
    if company_template:
        return company_template
    scored: list[tuple[int, str]] = []
    for template_name in INDUSTRY_TEMPLATES:
        terms = [template_name, *TEMPLATE_ALIASES.get(template_name, [])]
        score = _keyword_score(normalized, terms)
        if score > 0:
            scored.append((score, template_name))
    if not scored:
        return None
    scored.sort(key=lambda item: (-item[0], len(item[1])))
    return INDUSTRY_TEMPLATES[scored[0][1]]


def seed_candidates_for_node(node: IndustryNode, use_broad_fallback: bool = True) -> list[CandidateSeed]:
    exact = SEED_CANDIDATES.get(node.name)
    if exact:
        return exact

    node_terms = [node.name, *node.match_keywords]
    scored: list[tuple[int, str]] = []
    for seed_name in SEED_CANDIDATES:
        score = _keyword_score(seed_name, node_terms)
        if score > 0:
            scored.append((score, seed_name))
    if not scored:
        return BROAD_FALLBACK if use_broad_fallback else []

    scored.sort(key=lambda item: (-item[0], item[1]))
    merged: list[CandidateSeed] = []
    seen_codes: set[str] = set()
    for _, seed_name in scored[:3]:
        for code, name, reason, score in SEED_CANDIDATES[seed_name]:
            if code in seen_codes:
                continue
            seen_codes.add(code)
            merged.append((code, name, reason, score))
    return merged or (BROAD_FALLBACK if use_broad_fallback else [])


def _keyword_score(text: str, terms: list[str]) -> int:
    normalized_text = str(text).strip().lower()
    score = 0
    for index, term in enumerate(terms):
        normalized_term = str(term).strip().lower()
        if not normalized_term:
            continue
        if normalized_text == normalized_term:
            score += 200 - index
        elif normalized_term in normalized_text or normalized_text in normalized_term:
            score += 100 - index
        for token in _split_tokens(normalized_term):
            if token and token in normalized_text:
                score += 10
    return score


def _split_tokens(value: str) -> list[str]:
    tokens = [value]
    for separator in [" ", "/", "、", ",", "，", "-", "_", "与", "和", "及"]:
        next_tokens: list[str] = []
        for token in tokens:
            next_tokens.extend(token.split(separator))
        tokens = next_tokens
    return [token.strip() for token in tokens if len(token.strip()) >= 2]




